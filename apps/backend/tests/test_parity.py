PARITY = Path(__file__).resolve().parents[3] / "packages" / "domain" / "parity"
VECTORS: dict[str, Any] = json.loads((PARITY / "vectors.json").read_text(encoding="utf-8"))

# Cases per group when this port was written. A group that shrinks would
# silently weaken the guarantee, so the counts are pinned as minimums.
EXPECTED_MINIMUM = {
    "divRound": 40,
    "hourlyPay": 60,
    "dates": 60,
    "periods": 120,
    "stubTotals": 60,
    "ytd": 40,
    "federal": 300,
    "state": 204,
    "taxLines": 120,
    "nextStub": 60,
}


def cases(group: str) -> list[Any]:
    return [pytest.param(case, id=f"{group}-{index}") for index, case in enumerate(VECTORS[group])]


def test_tax_data_is_a_byte_identical_copy_of_the_generated_file() -> None:
    assert TAX_DATA_PATH.read_bytes() == (PARITY / "tax-data.json").read_bytes()


def test_every_vector_group_is_covered() -> None:
    assert VECTORS["version"] == 1
    groups = {name: len(value) for name, value in VECTORS.items() if name != "version"}
    assert groups.keys() == EXPECTED_MINIMUM.keys(), "a new group needs a parity test here"
    for name, minimum in EXPECTED_MINIMUM.items():
        assert groups[name] >= minimum, name


@pytest.mark.parametrize("case", cases("divRound"))
def test_div_round(case: dict[str, Any]) -> None:
    assert div_round_half_up(case["numerator"], case["divisor"]) == case["expected"]


@pytest.mark.parametrize("case", cases("hourlyPay"))
def test_hourly_pay(case: dict[str, Any]) -> None:
    assert pay_for_minutes(case["minutes"], case["rateCents"]) == case["expected"]
    assert overtime_rate_cents(case["rateCents"], case["overtimePct"]) == case["overtimeRateCents"]


@pytest.mark.parametrize("case", cases("dates"))
def test_dates(case: dict[str, Any]) -> None:
    assert add_days(case["date"], case["days"]) == case["added"]
    assert diff_days(case["date"], case["added"]) == case["diff"]


@pytest.mark.parametrize("case", cases("periods"))
def test_periods(case: dict[str, Any]) -> None:
    schedule, today = case["schedule"], case["today"]
    containing = period_containing(today, schedule)
    following = next_period(containing, schedule)
    pay_date = default_pay_date(containing)
    assert containing == case["containing"]
    assert following == case["next"]
    assert pay_date == case["defaultPayDate"]
    assert next_pay_date(containing, pay_date, following) == case["nextPayDate"]
    assert current_period(containing, schedule, case["laterToday"]) == case["currentAfterLatest"]
    assert current_period(None, schedule, case["laterToday"]) == case["currentWithNoStubs"]


@pytest.mark.parametrize("case", cases("stubTotals"))
def test_stub_totals(case: dict[str, Any]) -> None:
    assert [line_amount(line) for line in case["lines"]] == case["lineAmounts"]
    assert calc_stub(case["lines"]) == case["expected"]


@pytest.mark.parametrize("case", cases("ytd"))
def test_ytd(case: dict[str, Any]) -> None:
    target = next(stub for stub in case["stubs"] if stub["id"] == case["targetId"])
    totals = compute_ytd(target, case["stubs"], case["startingYtd"])
    expected = dict(case["expected"])
    assert prior_ytd_gross(target, case["stubs"], case["startingYtd"]) == expected.pop("priorYtdGrossCents")
    assert totals == expected
    # The vectors list byLine sorted by key; the same keys in the same order once sorted.
    assert sorted(totals["byLine"]) == list(expected["byLine"])


@pytest.mark.parametrize("case", cases("federal"))
def test_federal(case: dict[str, Any]) -> None:
    data = federal_tax_data(case["year"])
    assert data is not None
    assert PAY_PERIODS_PER_YEAR[case["schedule"]] == case["periodsPerYear"]
    wages, prior = case["wagesCents"], case["priorYtdWagesCents"]
    assert {
        "federalIncomeTaxCents": federal_income_tax(
            data=data, wages_cents=wages, periods_per_year=case["periodsPerYear"], w4=case["w4"]
        ),
        "socialSecurityCents": social_security_tax(data=data, wages_cents=wages, prior_ytd_wages_cents=prior),
        "medicareCents": medicare_tax(data=data, wages_cents=wages, prior_ytd_wages_cents=prior),
    } == case["expected"]


# State rules now live in the database (seeded from app/tax_rules/data). The
# TypeScript vectors still pin the states it calculated, the ones it did not, and
# those without the tax; a state the server has since learned to calculate is
# checked by its own tests in tests/tax_states instead.
SEED_RULES: dict[tuple[int, str], list[dict[str, Any]]] = {}
for _rule in seed_files():
    SEED_RULES.setdefault((_rule["year"], _rule["jurisdiction"]), []).append(dict(_rule))


def _rules(year: int, state: str | None) -> list[dict[str, Any]]:
    return SEED_RULES.get((year, state), []) if state else []


def _still_comparable(state: str | None, year: int, expected_kind: str) -> bool:
    income = next((rule for rule in _rules(year, state) if rule["tax"] == "income"), None)
    if state is None:
        return True
    if income is None:
        # A year with no rules loaded: the server leaves a line to type, whatever the state.
        return expected_kind == "manual"
    now = {"none": "none", "manual": "manual"}.get(income["method"], "amount")
    other_taxes = any(rule["tax"] != "income" and rule["method"] != "none" for rule in _rules(year, state))
    return now == expected_kind and not other_taxes


@pytest.mark.parametrize("case", cases("state"))
def test_state(case: dict[str, Any]) -> None:
    if not _still_comparable(case["state"], case["year"], case["expected"]["kind"]):
        pytest.skip("calculated by the server since the vectors were made; see tests/tax_states")
    inp = StateInput(
        year=case["year"],
        wages_cents=case["wagesCents"],
        periods_per_year=case["periodsPerYear"],
        w4=case["w4"],
        cert={**DEFAULT_STATE_W4, **case["stateW4"]},
    )
    lines = state_taxes(_rules(case["year"], case["state"]), case["state"], inp)
    income = next((line for line in lines if line["code"] == "sit"), None)
    if income is None:
        result: dict[str, Any] = {"kind": "none"}
    elif income["typed"]:
        result = {"kind": "manual"}
    else:
        result = {"kind": "amount", "cents": income["cents"]}
    assert result == case["expected"]


@pytest.mark.parametrize("case", cases("taxLines"))
def test_tax_lines(case: dict[str, Any]) -> None:
    context = dict(case["context"])
    state = work_state(context["profile"], context["businessState"])
    sit = next((line for line in case["expected"]["lines"] if line.get("taxCode") == "sit"), None)
    kind = "none" if sit is None else "manual" if sit["source"] == "manual" else "amount"
    if not _still_comparable(state, context["year"], kind):
        pytest.skip("calculated by the server since the vectors were made; see tests/tax_states")
    context["stateRules"] = _rules(context["year"], state)
    assert apply_taxes(case["input"], context) == case["expected"]  # type: ignore[arg-type]


@pytest.mark.parametrize("case", cases("nextStub"))
def test_next_stub(case: dict[str, Any]) -> None:
    schedule, today, pct = case["schedule"], case["today"], case["overtimePct"]
    assert draft_next_stub(case["worker"], schedule, None, today, pct) == case["first"]
    assert draft_next_stub(case["changedRate"], schedule, case["previous"], today, pct) == case["second"]
